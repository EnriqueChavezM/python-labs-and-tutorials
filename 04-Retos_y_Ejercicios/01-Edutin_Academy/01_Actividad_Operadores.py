#Pedir números al usuario
primer_num = int(input("Ingresa el primer número: "))
Segundo_num = int(input("Ingresar el segundo número: "))

#Operaciones aritméticas
print (f"la suma es: {primer_num + Segundo_num}")
print (f"la multiplicacion es: {primer_num * Segundo_num}")

#Operaciones de comparación
print (f"¿Los números son iguales?: {primer_num == Segundo_num}")
print(f"¿El primer número es menor que el segundo?: {primer_num < Segundo_num}")
print(f"¿El segundo número es mayor o igual al primero?: {primer_num >= Segundo_num}")
