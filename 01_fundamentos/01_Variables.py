nombre = "Enrique"      #variable de tipo string
numero = 1234567890     #variable de tipo integer
altura = 1.80           #variable de tipo float
x = True                #variable de tipo boolean

#Concatenar variable
print ("Hala " + nombre + " bienvedo al mundo de la programacion con python")

#Casting de variable ina a str
print("Hala " + nombre + " tu numero es: " + str(numero))

#cadenas F
print(f"Hala {nombre} tu altura es: {altura}")
print(f"Hala {nombre} tu estado es: {x}")

#Tipo de variable
print(type(nombre))
print(type(numero))
print(type(altura))
print(type(x))